func TestProcessDueJobsBelowThresholdCompletesWithoutDiary(t *testing.T) {
	now := dayMS(2026, 5, 2, 0, 10)
	userID := uuid.New()
	job := AIDiaryJob{UserID: userID, TargetDate: testDate(2026, 5, 1)}

	store := newFakeAIDiaryStore()
	store.due = []AIDiaryJob{job}
	store.memos = []domain.Memo{testMemo(userID, "too short", dayMS(2026, 5, 1, 12, 0))}
	chat := &fakeAIDiaryChat{reply: `{"summary":"x","moodKey":"calm","moodScore":5}`}

	processed, err := newTestService(store, fakeAIDiarySettings{}, chat, now).
		ProcessDueJobs(context.Background())
	if err != nil {
		t.Fatalf("ProcessDueJobs: %v", err)
	}
	if processed != 1 {
		t.Errorf("processed = %d, want 1", processed)
	}
	if len(store.saved) != 0 || chat.calls != 0 {
		t.Errorf("saved=%d chatCalls=%d, want 0 below the threshold", len(store.saved), chat.calls)
	}
	if len(store.failed) != 0 {
		t.Errorf("failed jobs = %d, want 0 (a skip is not a failure)", len(store.failed))
	}
	if len(store.completed) != 1 || store.completed[0] != job {
		t.Errorf("completed = %+v, want [%+v]", store.completed, job)
	}
}

func TestProcessDueJobsGeneratesAutoDiary(t *testing.T) {
	now := dayMS(2026, 5, 2, 0, 10)
	userID := uuid.New()
	target := testDate(2026, 5, 1)
	job := AIDiaryJob{UserID: userID, TargetDate: target}

	store := newFakeAIDiaryStore()
	store.due = []AIDiaryJob{job}
	store.memos = twoLongMemos(userID)
	chat := &fakeAIDiaryChat{reply: `{"summary":"a reflective day","moodKey":"calm","moodScore":7}`}

	if _, err := newTestService(store, fakeAIDiarySettings{}, chat, now).
		ProcessDueJobs(context.Background()); err != nil {
		t.Fatalf("ProcessDueJobs: %v", err)
	}
	if len(store.saved) != 1 || chat.calls != 1 {
		t.Fatalf("saved=%d chatCalls=%d, want 1 each", len(store.saved), chat.calls)
	}
	if len(chat.requests[0].Messages) != 3 {
		t.Errorf("prompt messages = %d, want 3 (preamble + 2 memos)", len(chat.requests[0].Messages))
	}

	diary, err := store.DiaryForDate(context.Background(), userID, target)
	if err != nil {
		t.Fatalf("DiaryForDate: %v", err)
	}
	if diary.GenerationSource != domain.GenerationSourceAI {
		t.Errorf("generation source = %q, want %q", diary.GenerationSource, domain.GenerationSourceAI)
	}
	if diary.AutoGenerationLocked {
		t.Error("auto-generated diary is locked, want unlocked")
	}
	if diary.LastAutoGeneratedAt == nil || *diary.LastAutoGeneratedAt != now {
		t.Errorf("last auto generated at = %v, want %d", diary.LastAutoGeneratedAt, now)
	}
	if len(diary.GeneratedFromMemoIDs) != 2 {
		t.Errorf("generated from %d memos, want 2", len(diary.GeneratedFromMemoIDs))
	}
	if len(store.failed) != 0 || len(store.completed) != 1 {
		t.Errorf("failed=%d completed=%d, want 0 and 1", len(store.failed), len(store.completed))
	}
}

func TestProcessDueJobsDoesNotOverwriteLockedDiary(t *testing.T) {
	now := dayMS(2026, 5, 2, 0, 10)
	userID := uuid.New()
	target := testDate(2026, 5, 1)
	job := AIDiaryJob{UserID: userID, TargetDate: target}

	store := newFakeAIDiaryStore()
	store.due = []AIDiaryJob{job}
	store.memos = twoLongMemos(userID)
	store.diaries[fakeJobKey(userID, target)] = domain.Diary{
		Date: target, UserID: userID, Summary: "hand written",
		GenerationSource: domain.GenerationSourceManual, AutoGenerationLocked: true,
	}
	chat := &fakeAIDiaryChat{reply: `{"summary":"should not land","moodKey":"calm","moodScore":7}`}

	if _, err := newTestService(store, fakeAIDiarySettings{}, chat, now).
		ProcessDueJobs(context.Background()); err != nil {
		t.Fatalf("ProcessDueJobs: %v", err)
	}
	if chat.calls != 0 || len(store.saved) != 0 {
		t.Errorf("chatCalls=%d saved=%d, want 0 for a locked diary", chat.calls, len(store.saved))
	}
	diary, err := store.DiaryForDate(context.Background(), userID, target)
	if err != nil {
		t.Fatalf("DiaryForDate: %v", err)
	}
	if diary.Summary != "hand written" || !diary.AutoGenerationLocked {
		t.Errorf("locked diary = %+v, want it untouched", diary)
	}
}

func TestProcessDueJobsProviderFailureLeavesJobRetryable(t *testing.T) {
	now := dayMS(2026, 5, 2, 0, 10)
	userID := uuid.New()
	target := testDate(2026, 5, 1)
	job := AIDiaryJob{UserID: userID, TargetDate: target}

	store := newFakeAIDiaryStore()
	store.due = []AIDiaryJob{job}
	store.memos = twoLongMemos(userID)
	chat := &fakeAIDiaryChat{err: errors.New("provider exploded")}

	// A per-job failure must not fail the sweep.
	if _, err := newTestService(store, fakeAIDiarySettings{}, chat, now).
		ProcessDueJobs(context.Background()); err != nil {
		t.Fatalf("ProcessDueJobs should not fail on a per-job error: %v", err)
	}
	if len(store.saved) != 0 || len(store.completed) != 0 {
		t.Errorf("saved=%d completed=%d, want 0 after a provider failure",
			len(store.saved), len(store.completed))
	}
	if len(store.failed) != 1 {
		t.Fatalf("failed jobs = %d, want 1", len(store.failed))
	}
	failed := store.failed[0]
	if failed.job != job {
		t.Errorf("failed job = %+v, want %+v", failed.job, job)
	}
	if !strings.Contains(failed.lastError, "provider exploded") {
		t.Errorf("last error = %q, want it to carry the provider failure", failed.lastError)
	}
	if want := now + aiDiaryRetryDelayMS; failed.runAfter != want {
		t.Errorf("retry run after = %d, want %d", failed.runAfter, want)
	}
}

func TestQueueJobForMemoUsesMemoDayAndNextDayRunTime(t *testing.T) {
	now := dayMS(2026, 5, 1, 23, 0)
	userID := uuid.New()
	memo := testMemo(userID, "late night thought", now)

	store := newFakeAIDiaryStore()
	if err := newTestService(store, fakeAIDiarySettings{}, &fakeAIDiaryChat{}, now).
		QueueJobForMemo(context.Background(), memo); err != nil {
		t.Fatalf("QueueJobForMemo: %v", err)
	}
	if len(store.enqueued) != 1 {
		t.Fatalf("enqueued jobs = %d, want 1", len(store.enqueued))
	}
	enqueued := store.enqueued[0]
	if enqueued.userID != userID || enqueued.date.String() != "2026-05-01" {
		t.Errorf("enqueued = %+v, want user %s on 2026-05-01", enqueued, userID)
	}
	if want := ComputeRunAfter(enqueued.date, testLoc); enqueued.runAfter != want {
		t.Errorf("run after = %d, want %d", enqueued.runAfter, want)
	}
	if enqueued.now != now {
		t.Errorf("enqueued now = %d, want %d", enqueued.now, now)
	}
}

