func TestParseAIDiaryPayloadValidates(t *testing.T) {
	payload, err := ParseAIDiaryPayload(`here: {"summary":"  a day  ","moodKey":"joy","moodScore":9}`)
	if err != nil {
		t.Fatalf("ParseAIDiaryPayload: %v", err)
	}
	if payload.Summary != "a day" || payload.MoodKey != "joy" || payload.MoodScore != 9 {
		t.Errorf("payload = %+v, want trimmed summary and parsed mood", payload)
	}
	for _, raw := range []string{
		"no json here",
		`{"summary":"","moodKey":"joy","moodScore":5}`,
		`{"summary":"x","moodKey":"unknown","moodScore":5}`,
		`{"summary":"x","moodKey":"joy","moodScore":0}`,
		`{"summary":"x","moodKey":"joy","moodScore":11}`,
	} {
		if _, err := ParseAIDiaryPayload(raw); err == nil {
			t.Errorf("ParseAIDiaryPayload(%q) succeeded, want an error", raw)
		}
	}
}

