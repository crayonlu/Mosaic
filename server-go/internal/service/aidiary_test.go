type fakeEnqueuedJob struct {
	userID   uuid.UUID
	date     domain.Date
	runAfter int64
	now      int64
}

type fakeSavedDiary struct {
	userID    uuid.UUID
	date      domain.Date
	summary   string
	moodKey   string
	moodScore int32
	memoIDs   []uuid.UUID
	now       int64
}

type fakeFailedJob struct {
	job       AIDiaryJob
	lastError string
	runAfter  int64
}

type fakeAIDiaryStore struct {
	due       []AIDiaryJob
	diaries   map[string]domain.Diary
	memos     []domain.Memo
	enqueued  []fakeEnqueuedJob
	saved     []fakeSavedDiary
	completed []AIDiaryJob
	failed    []fakeFailedJob
}

func newFakeAIDiaryStore() *fakeAIDiaryStore {
	return &fakeAIDiaryStore{diaries: map[string]domain.Diary{}}
}

func fakeJobKey(userID uuid.UUID, date domain.Date) string {
	return userID.String() + "|" + date.String()
}

func (f *fakeAIDiaryStore) EnqueueJob(
	_ context.Context, userID uuid.UUID, targetDate domain.Date, runAfterMS, now int64,
) error {
	f.enqueued = append(f.enqueued, fakeEnqueuedJob{userID, targetDate, runAfterMS, now})
	return nil
}

func (f *fakeAIDiaryStore) ClaimDueJobs(context.Context, int64, int) ([]AIDiaryJob, error) {
	claimed := f.due
	f.due = nil
	return claimed, nil
}

func (f *fakeAIDiaryStore) CompleteJob(
	_ context.Context, userID uuid.UUID, targetDate domain.Date, _ int64,
) error {
	f.completed = append(f.completed, AIDiaryJob{UserID: userID, TargetDate: targetDate})
	return nil
}

func (f *fakeAIDiaryStore) FailJob(
	_ context.Context, userID uuid.UUID, targetDate domain.Date, lastError string, runAfterMS, _ int64,
) error {
	f.failed = append(f.failed, fakeFailedJob{
		job:       AIDiaryJob{UserID: userID, TargetDate: targetDate},
		lastError: lastError, runAfter: runAfterMS,
	})
	return nil
}

func (f *fakeAIDiaryStore) DiaryForDate(
	_ context.Context, userID uuid.UUID, targetDate domain.Date,
) (domain.Diary, error) {
	diary, ok := f.diaries[fakeJobKey(userID, targetDate)]
	if !ok {
		return domain.Diary{}, domain.ErrNoRows
	}
	return diary, nil
}

func (f *fakeAIDiaryStore) CandidateMemos(
	context.Context, uuid.UUID, int64, int64,
) ([]domain.Memo, error) {
	return f.memos, nil
}

// SaveGeneratedDiary models the real store's guarded upsert: a locked diary is
// never overwritten and a successful write is tagged as auto-generated.
func (f *fakeAIDiaryStore) SaveGeneratedDiary(
	_ context.Context, userID uuid.UUID, targetDate domain.Date,
	summary, moodKey string, moodScore int32, memoIDs []uuid.UUID, now int64,
) error {
	f.saved = append(f.saved, fakeSavedDiary{
		userID: userID, date: targetDate, summary: summary, moodKey: moodKey,
		moodScore: moodScore, memoIDs: memoIDs, now: now,
	})
	key := fakeJobKey(userID, targetDate)
	if existing, ok := f.diaries[key]; ok && existing.AutoGenerationLocked {
		return nil
	}
	f.diaries[key] = domain.Diary{
		Date: targetDate, UserID: userID, Summary: summary, MoodKey: moodKey,
		MoodScore: moodScore, GenerationSource: domain.GenerationSourceAI,
		GeneratedFromMemoIDs: memoIDs, LastAutoGeneratedAt: &now, CreatedAt: now, UpdatedAt: now,
	}
	return nil
}

// --- helpers ---------------------------------------------------------------

var testLoc = time.FixedZone("CST", 8*60*60)

func testDate(y int, m time.Month, d int) domain.Date {
	return domain.NewDate(time.Date(y, m, d, 0, 0, 0, 0, testLoc))
}

func dayMS(y int, m time.Month, d, hour, minute int) int64 {
	return time.Date(y, m, d, hour, minute, 0, 0, testLoc).UnixMilli()
}

func testMemo(userID uuid.UUID, content string, createdAt int64) domain.Memo {
	return domain.Memo{ID: uuid.New(), UserID: userID, Content: content, CreatedAt: createdAt}
}

// twoLongMemos gives a day enough material to clear the default thresholds.
func twoLongMemos(userID uuid.UUID) []domain.Memo {
	return []domain.Memo{
		testMemo(userID, strings.Repeat("a", 200), dayMS(2026, 5, 1, 9, 0)),
		testMemo(userID, strings.Repeat("b", 200), dayMS(2026, 5, 1, 20, 0)),
	}
}

func fastRetryPolicy() retry.Policy {
	return retry.Policy{
		MaxRetries: 0, Timeout: time.Second,
		Backoff: func(int) time.Duration { return 0 },
		Sleep:   func(context.Context, time.Duration) error { return nil },
	}
}

func newTestService(
	store AIDiaryStore, settings AIDiarySettings, chat AIDiaryChatClient, now int64,
) *AIDiaryService {
	return NewAIDiaryService(
		store, settings, fakeAIDiaryTimezone{loc: testLoc},
		fakeAIDiaryConfigs{config: domain.AIConfig{
			Provider: "openai", BaseURL: "https://example.test", APIKey: "key", Model: "model",
		}},
		chat,
		fakeAIDiaryImages{},
	).WithClock(func() int64 { return now }).WithRetryPolicy(fastRetryPolicy())
}

