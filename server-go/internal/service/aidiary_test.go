func TestComputeRunAfter(t *testing.T) {
	cases := []struct {
		name     string
		loc      *time.Location
		target   domain.Date
		wantDate string
	}{
		{"next day in UTC+8", testLoc, testDate(2026, 5, 1), "2026-05-02T00:05:00+08:00"},
		{"rolls over the month in UTC", time.UTC, domain.NewDate(time.Date(2026, 1, 31, 0, 0, 0, 0, time.UTC)), "2026-02-01T00:05:00Z"},
	}
	for _, tc := range cases {
		got := time.UnixMilli(ComputeRunAfter(tc.target, tc.loc)).In(tc.loc).Format(time.RFC3339)
		if got != tc.wantDate {
			t.Errorf("%s: ComputeRunAfter = %s, want %s", tc.name, got, tc.wantDate)
		}
	}
}

func TestDateFromTimestampAppliesTimezone(t *testing.T) {
	ts := time.Date(2026, 5, 1, 16, 30, 0, 0, time.UTC).UnixMilli()
	if got := DateFromTimestamp(ts, time.UTC).String(); got != "2026-05-01" {
		t.Errorf("UTC date = %q, want 2026-05-01", got)
	}
	if got := DateFromTimestamp(ts, testLoc).String(); got != "2026-05-02" {
		t.Errorf("UTC+8 date = %q, want 2026-05-02 (next day)", got)
	}
}

func TestShouldGenerateDiaryBoundary(t *testing.T) {
	const minMemos, minChars = 2, 150
	cases := []struct {
		name         string
		memos, chars int
		want         bool
	}{
		{"exactly at both thresholds", 2, 150, true},
		{"one char short at min memos", 2, 149, false},
		{"one char over at min memos", 2, 151, true},
		{"extra memo overrides char shortfall", 3, 0, true},
		{"below min memos with plenty of chars", 1, 10000, false},
		{"no content", 0, 0, false},
	}
	for _, tc := range cases {
		if got := ShouldGenerateDiary(tc.memos, tc.chars, minMemos, minChars); got != tc.want {
			t.Errorf("%s: ShouldGenerateDiary(%d, %d) = %v, want %v",
				tc.name, tc.memos, tc.chars, got, tc.want)
		}
	}
}

