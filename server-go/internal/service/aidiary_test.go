type fakeAIDiarySettings struct{ values map[string]string }

func (f fakeAIDiarySettings) Bool(_ context.Context, key string, fallback bool) bool {
	switch f.values[key] {
	case "true":
		return true
	case "false":
		return false
	default:
		return fallback
	}
}

func (f fakeAIDiarySettings) Int(_ context.Context, key string, fallback int32) int32 {
	parsed, err := strconv.Atoi(f.values[key])
	if err != nil {
		return fallback
	}
	return int32(parsed)
}

