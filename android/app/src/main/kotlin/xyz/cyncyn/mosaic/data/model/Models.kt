@Serializable
data class MemoRevision(
    val id: String,
    val memoId: String,
    val revisionNumber: Int = 1,
    val content: String,
    val tags: List<String> = emptyList(),
    val aiSummary: String? = null,
    val createdAt: Long = 0,
)

@Serializable
data class BotSummary(
    val id: String,
    val name: String,
