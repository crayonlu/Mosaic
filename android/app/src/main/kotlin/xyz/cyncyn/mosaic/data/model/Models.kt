@Serializable
data class TagCount(
    val tag: String,
    val count: Int = 0,
)

@Serializable
data class SearchMemosResponse(
    val memos: List<MemoWithResources> = emptyList(),
    val total: Int = 0,
    val page: Int = 1,
    val pageSize: Int = 50,
    val semanticEnabled: Boolean = false,
)

@Serializable
data class HeatmapResponse(
    val dates: List<String> = emptyList(),
    val counts: List<Int> = emptyList(),
    val moods: List<String?> = emptyList(),
    val moodScores: List<Int?> = emptyList(),
)

@Serializable
data class SyncCursors(
    val memo: Long? = null,
    val diary: Long? = null,
    val resource: Long? = null,
    val bot: Long? = null,
) {
    companion object {
        val EMPTY = SyncCursors()
    }
}

@Serializable
data class EntityChanges<T>(
    val updated: List<T> = emptyList(),
    val deletedIds: List<String> = emptyList(),
) {
    val changeCount: Int get() = updated.size + deletedIds.size
}

@Serializable
data class SyncEntityChanges(
    val memo: EntityChanges<MemoWithResources> = EntityChanges(),
    val diary: EntityChanges<DiaryResponse> = EntityChanges(),
    val resource: EntityChanges<ResourceResponse> = EntityChanges(),
    val bot: EntityChanges<BotResponse> = EntityChanges(),
) {
    val totalChanges: Int get() = memo.changeCount + diary.changeCount + resource.changeCount + bot.changeCount
}

@Serializable
data class SyncPullResponse(
    val cursors: SyncCursors = SyncCursors(),
    val changes: SyncEntityChanges = SyncEntityChanges(),
)

@Serializable
data class SyncResult(
    val pulled: Int,
    val cursors: SyncCursors,
    val rounds: Int,
)

@Serializable
data class PaginatedResponse<T>(
    val items: List<T> = emptyList(),
    val total: Int = 0,
    val page: Int = 1,
    val pageSize: Int = 20,
    val totalPages: Int = 1,
)
