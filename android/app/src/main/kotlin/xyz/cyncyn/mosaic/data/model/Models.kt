    val thinkingContent: String? = null,
    val parentReplyId: String? = null,
    val userQuestion: String? = null,
    val revisionNumber: Int? = null,
    val createdAt: Long = 0,
    val children: List<BotReply> = emptyList(),
    val threadCount: Int = 0,
    val latestReplyId: String? = null,
)

@Serializable
data class MemoDetail(
    val memo: MemoWithResources,
    val revisions: List<MemoRevision> = emptyList(),
    val botReplies: List<BotReply> = emptyList(),
)

@Serializable
