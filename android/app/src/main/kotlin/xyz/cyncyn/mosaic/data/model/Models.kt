package xyz.cyncyn.mosaic.data.model

import kotlinx.serialization.Serializable

/** All DTOs follow docs/server-api.md v2.6: camelCase fields, ms timestamps. */

@Serializable
data class UserResponse(
    val id: String,
    val username: String,
    val avatarUrl: String? = null,
    val createdAt: Long = 0,
    val updatedAt: Long = 0,
)

@Serializable
data class AuthTokens(
    val accessToken: String,
    val refreshToken: String,
)

@Serializable
data class LoginResponse(
    val accessToken: String,
    val refreshToken: String,
    val user: UserResponse? = null,
)

@Serializable
data class RefreshResponse(
    val accessToken: String,
    val refreshToken: String,
)

@Serializable
data class HealthResponse(
    val status: String = "",
    val version: String = "",
)

@Serializable
data class ResourceResponse(
    val id: String,
    val memoId: String? = null,
    val filename: String = "",
    val resourceType: String = "image",
    val mimeType: String = "application/octet-stream",
    val fileSize: Long = 0,
    val storageType: String = "local",
    val url: String = "",
    val thumbnailUrl: String? = null,
    val metadata: kotlinx.serialization.json.JsonObject? = null,
    val createdAt: Long = 0,
    val updatedAt: Long? = null,
)

@Serializable
data class MemoWithResources(
    val id: String,
    val content: String,
    val tags: List<String> = emptyList(),
    val isArchived: Boolean = false,
