class AuthedTransportTest {

    @Test
    fun `401 triggers refresh and retries original request`() = runTest {
        val tokenStore = MemoryTokenStore(AuthTokens("expired-token", "refresh-1"))
        val api = MosaicApi(
            AuthedTransport(
                FakeTransport(
                    rule({ it.path == "/api/auth/refresh" }) {
                        response(200, """{"accessToken":"fresh-token","refreshToken":"refresh-2"}""")
                    },
                    rule({ it.path == "/api/auth/me" }) { req ->
                        if (req.headers["Authorization"] == "Bearer fresh-token") {
                            response(200, """{"id":"u1","username":"admin"}""")
                        } else {
                            response(401, """{"error":"401 Unauthorized","message":"Invalid token"}""")
                        }
                    },
                ),
                tokenStore,
            ),
        )

        val user = api.me()

        assertEquals("admin", user.username)
        assertEquals("fresh-token", tokenStore.tokensValue?.accessToken)
        assertEquals("refresh-2", tokenStore.tokensValue?.refreshToken)
    }

    @Test
    fun `failed refresh clears session and throws AuthException`() = runTest {
        val tokenStore = MemoryTokenStore(AuthTokens("expired-token", "dead-refresh"))
        val api = MosaicApi(
            AuthedTransport(
                FakeTransport(
                    rule({ it.path == "/api/auth/me" }) { response(401, """{"error":"401 Unauthorized","message":"Invalid token"}""") },
                    rule({ it.path == "/api/auth/refresh" }) { response(401, """{"error":"401 Unauthorized","message":"Invalid refresh token"}""") },
                ),
                tokenStore,
            ),
        )

        val e = runCatching { api.me() }.exceptionOrNull()

        assertTrue(e is AuthException)
        assertNull(tokenStore.tokensValue)
        assertEquals(1, tokenStore.cleared)
    }

    @Test
    fun `auth endpoints are never retried or decorated`() = runTest {
        val tokenStore = MemoryTokenStore(AuthTokens("t", "r"))
        val requests = mutableListOf<ApiRequest>()
        val api = MosaicApi(
            AuthedTransport(
                object : xyz.cyncyn.mosaic.data.net.HttpTransport {
                    override suspend fun execute(request: ApiRequest): xyz.cyncyn.mosaic.data.net.ApiResponse {
                        requests.add(request)
                        if (request.path == "/api/auth/login") {
                            return response(200, LOGIN_JSON)
                        }
                        return response(401)
                    }
                },
                tokenStore,
            ),
        )

        val login = api.login("admin", "admin123")

        assertEquals("access-abc", login.accessToken)
        val loginRequest = requests.single()
        assertNull(loginRequest.headers["Authorization"])
    }
}

