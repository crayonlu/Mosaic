class ContractParsingTest {

    private val json = xyz.cyncyn.mosaic.data.net.MosaicJson

    @Test
    fun `memo with resources parses doc example`() {
        val memo = json.decodeFromString<MemoWithResources>(MEMO_JSON.trimIndent())

        assertEquals("uuid-1", memo.id)
        assertEquals("今天完成了接口联调", memo.content)
        assertEquals(listOf("work", "api"), memo.tags)
        assertEquals("2026-02-24", memo.diaryDate)
        assertEquals("可选的 AI 摘要", memo.aiSummary)
        assertEquals(2, memo.revisionCount)
        assertEquals(1, memo.resources.size)
        assertEquals("image.png", memo.resources.first().filename)
        assertEquals(1920, memo.resources.first().metadata?.get("width")?.toString()?.toInt())
        assertEquals("/api/resources/res-1/download", memo.resources.first().url)
    }

    @Test
    fun `sync pull response parses entity changes`() {
        val pull = json.decodeFromString<xyz.cyncyn.mosaic.data.model.SyncPullResponse>(SYNC_PULL_JSON.trimIndent())

        assertEquals(1700000005000L, pull.cursors.memo)
        assertEquals(1, pull.changes.memo.updated.size)
        assertEquals(listOf("deleted-uuid"), pull.changes.memo.deletedIds)
        assertEquals("joy", pull.changes.diary.updated.first().moodKey)
        assertEquals(3, pull.changes.totalChanges)
    }

    @Test
    fun `search response parses hybrid fields`() {
        val search = json.decodeFromString<xyz.cyncyn.mosaic.data.model.SearchMemosResponse>(SEARCH_JSON.trimIndent())

        assertTrue(search.semanticEnabled)
        assertEquals(10, search.total)
        val memo = search.memos.single()
        assertEquals(0.85, memo.semanticScore!!, 1e-9)
        assertEquals(0.72, memo.keywordScore!!, 1e-9)
        assertEquals("hybrid", memo.matchType)
    }

    @Test
    fun `login response parses user`() {
        val login = json.decodeFromString<xyz.cyncyn.mosaic.data.model.LoginResponse>(LOGIN_JSON.trimIndent())
        assertEquals("access-abc", login.accessToken)
        assertEquals("admin", login.user?.username)
        assertNull(login.user?.avatarUrl)
    }

    @Test
    fun `diary with memos parses doc example`() {
        val diary = json.decodeFromString<DiaryResponse>(
            DIARY_DETAIL_JSON.trimIndent().let { text ->
                // DiaryWithMemos superset also decodes as DiaryResponse minus memos
                text
            },
        )
        assertEquals("2026-02-24", diary.date)
    }

    @Test
    fun `unknown fields are ignored`() {
        val memo = json.decodeFromString<MemoWithResources>(
            """{"id":"x","content":"y","someFutureField":{"nested":true}}""",
        )
        assertEquals("x", memo.id)
        assertEquals("y", memo.content)
    }
}

