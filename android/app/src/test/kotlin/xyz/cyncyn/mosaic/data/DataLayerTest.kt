class FileLocalStoreTest {

    @Test
    fun `cache survives across store instances like a process restart`() = runTest {
        val dir = java.nio.file.Files.createTempDirectory("mosaic-cache").toFile()
        val resource = ResourceResponse(
            id = "res-1",
            filename = "sunset.png",
            resourceType = "image",
            mimeType = "image/png",
            url = "/api/resources/res-1/download",
            createdAt = 42L,
        )
        val first = xyz.cyncyn.mosaic.data.store.FileLocalStore(dir)
        first.upsertMemos(listOf(MemoWithResources(id = "m1", content = "跨进程存活的 memo", createdAt = 1, updatedAt = 1)))
        first.upsertDiaries(listOf(DiaryResponse(date = "2026-09-21", summary = "跨进程存活的日记", moodKey = "calm", moodScore = 72)))
        first.upsertResources(listOf(resource))
        first.updateCursors(SyncCursors(memo = 99L))

        // "new process": fresh instance over the same directory
        val second = xyz.cyncyn.mosaic.data.store.FileLocalStore(dir)

        assertEquals("跨进程存活的 memo", second.allMemos().single().content)
        assertEquals("跨进程存活的日记", second.getDiary("2026-09-21")!!.summary)
        assertEquals("sunset.png", second.allResources().single().filename)
        assertEquals(99L, second.getCursors().memo)
        dir.deleteRecursively()
    }
}
