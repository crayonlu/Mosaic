class SyncEngineTest {

    private fun storeWithApi(handler: (ApiRequest) -> xyz.cyncyn.mosaic.data.net.ApiResponse): Pair<LocalStore, SyncEngine> {
        val store = InMemoryLocalStore()
        val api = MosaicApi(FakeTransport(rule({ it.path == "/api/sync/pull" }) { handler(it) }))
        return store to SyncEngine(api, store, clientId = "test-client")
    }

    @Test
    fun `pull - apply - advance cursor`() = runTest {
        val (store, engine) = storeWithApi { response(200, SYNC_PULL_JSON) }

        val result = engine.syncOnce()

        assertEquals(3, result.pulled) // 1 memo update + 1 memo delete + 1 diary update
        // store received the real change set
        val memo = store.getMemo("uuid-1")
        assertNotNull(memo)
        assertEquals("今天完成了接口联调", memo!!.content)
        assertEquals("2026-02-24", memo.diaryDate)
        assertEquals(1700000005000L, memo.updatedAt)
        assertEquals("joy", store.getDiary("2026-02-24")?.moodKey)
        assertEquals(80, store.getDiary("2026-02-24")?.moodScore)
        // deleted id removed (was never present, so still absent) and cursor advanced
        assertEquals(1700000005000L, store.getCursors().memo)
        assertEquals(1700000005000L, store.getCursors().diary)
        assertNull(store.getCursors().resource)
    }

    @Test
    fun `second pull with advanced cursor only fetches new changes`() = runTest {
        var pullCount = 0
        val seedMemo = MemoWithResources(
            id = "old-1",
            content = "第一次全量拉到的旧 memo",
            createdAt = 1700000000000L,
            updatedAt = 1700000000000L,
        )
        val (store, engine) = storeWithApi { _ ->
            pullCount += 1
            response(
                200,
                if (pullCount == 1) {
                    """
                    {
                      "cursors": { "memo": 1700000005000 },
                      "changes": { "memo": { "updated": [{"id":"old-1","content":"第一次全量拉到的旧 memo","tags":[],"isArchived":false,"createdAt":1700000000000,"updatedAt":1700000005000,"revisionCount":1,"resources":[]}], "deletedIds": [] } }
                    }
                    """
                } else {
                    """
                    {
                      "cursors": { "memo": 1700000010000 },
                      "changes": { "memo": { "updated": [{"id":"new-1","content":"存根后注入的新条目","tags":["注入"],"isArchived":false,"createdAt":1700000010000,"updatedAt":1700000010000,"revisionCount":1,"resources":[]}], "deletedIds": [] } }
                    }
                    """
                },
            )
        }
        store.upsertMemos(listOf(seedMemo))

        val first = engine.syncOnce()
        assertEquals(1, first.pulled)
        val cursorsAfterFirst = store.getCursors()
        assertEquals(1700000005000L, cursorsAfterFirst.memo)

        val second = engine.syncOnce()
        assertEquals(1, second.pulled)
        assertEquals("存根后注入的新条目", store.getMemo("new-1")!!.content)
        assertEquals(1700000010000L, store.getCursors().memo)
        // both pulls were issued with the store's live cursors (monotonic)
        assertTrue(second.rounds == 1)
    }

    @Test
    fun `syncAll loops until empty delta`() = runTest {
        var round = 0
        val (store, engine) = storeWithApi { _ ->
            round += 1
            response(
                200,
                if (round <= 2) {
                    val id = "batch-$round"
                    """
                    {
                      "cursors": { "memo": 170000000${round}000 },
                      "changes": { "memo": { "updated": [{"id":"$id","content":"批量 $round","tags":[],"isArchived":false,"createdAt":170000000${round}000,"updatedAt":170000000${round}000,"revisionCount":1,"resources":[]}], "deletedIds": [] } }
                    }
                    """
                } else {
                    """{ "cursors": { "memo": 1700000010000 }, "changes": { "memo": { "updated": [], "deletedIds": [] } } }"""
                },
            )
        }

        val result = engine.syncAll()

        assertEquals(3, result.rounds)
        assertEquals(2, result.pulled)
        assertEquals("批量 1", store.getMemo("batch-1")!!.content)
        assertEquals("批量 2", store.getMemo("batch-2")!!.content)
    }

    @Test
    fun `deletions remove cached entities`() = runTest {
        val store = InMemoryLocalStore()
        store.upsertMemos(listOf(MemoWithResources(id = "gone-1", content = "将被删除", createdAt = 1, updatedAt = 1)))
        val api = MosaicApi(
            FakeTransport(
                rule({ it.path == "/api/sync/pull" }) {
                    response(
                        200,
                        """{ "cursors": { "memo": 1700000010000 }, "changes": { "memo": { "updated": [], "deletedIds": ["gone-1"] } } }""",
                    )
                },
            ),
        )
        SyncEngine(api, store, "test-client").syncOnce()
        assertNull(store.getMemo("gone-1"))
    }
}

