/** Scripted fake transport: first matching rule answers each request. */
private class ApiRule(
    val matches: (ApiRequest) -> Boolean,
    val handler: (ApiRequest) -> xyz.cyncyn.mosaic.data.net.ApiResponse,
)

private fun rule(
    matches: (ApiRequest) -> Boolean,
    handler: (ApiRequest) -> xyz.cyncyn.mosaic.data.net.ApiResponse,
): ApiRule = ApiRule(matches, handler)

private class FakeTransport(
    vararg rules: ApiRule,
) : xyz.cyncyn.mosaic.data.net.HttpTransport {
    val requests = mutableListOf<ApiRequest>()
    private val ruleList = rules.toList()

    override suspend fun execute(request: ApiRequest): xyz.cyncyn.mosaic.data.net.ApiResponse {
        requests.add(request)
        val matched = ruleList.firstOrNull { it.matches(request) }
            ?: error("no rule for ${request.method} ${request.path}")
        return matched.handler(request)
    }
}

private fun response(status: Int, body: String = "") =
    xyz.cyncyn.mosaic.data.net.ApiResponse(status, body.toByteArray())

private class MemoryTokenStore(initial: AuthTokens? = null) : TokenStore {
    var tokensValue: AuthTokens? = initial
    var userValue: UserResponse? = null
    var cleared = 0

    override suspend fun tokens(): AuthTokens? = tokensValue
    override suspend fun save(tokens: AuthTokens) {
        tokensValue = tokens
    }

    override suspend fun clear() {
        tokensValue = null
        cleared += 1
    }

    override suspend fun saveUser(user: UserResponse) {
        userValue = user
    }

    override suspend fun user(): UserResponse? = userValue
}

