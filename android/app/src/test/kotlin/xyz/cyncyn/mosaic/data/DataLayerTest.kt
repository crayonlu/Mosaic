class MosaicApiRequestTest {

    @Test
    fun `sync pull request body carries clientId and cursors`() = runTest {
        var captured: ApiRequest? = null
        val api = MosaicApi(FakeTransport(rule({ true }) { req ->
            captured = req
            response(200, """{ "cursors": {}, "changes": {} }""")
        }))
        api.syncPull("device-1", SyncCursors(memo = 42L))

        val body = captured!!.bodyUtf8()!!
        assertTrue(body.contains("\"clientId\":\"device-1\""))
        assertTrue(body.contains("\"memo\":42"))
        assertEquals("POST", captured!!.method)
        assertEquals("/api/sync/pull", captured!!.path)
    }

    @Test
    fun `search request repeats the tags query parameter`() = runTest {
        var captured: ApiRequest? = null
        val api = MosaicApi(FakeTransport(rule({ true }) { req ->
            captured = req
            response(200, SEARCH_JSON)
        }))
        api.searchMemos("设计", tags = listOf("工作", "生活"), startDate = "2026-09-01")

        val query = captured!!.query
        assertTrue(query.count { it.first == "query" && it.second == "设计" } == 1)
        assertTrue(query.count { it.first == "tags[]" && it.second == "工作" } == 1)
        assertTrue(query.count { it.first == "tags[]" && it.second == "生活" } == 1)
        assertEquals("2026-09-01", query.first { it.first == "startDate" }.second)
    }

    @Test
    fun `http errors surface contract message`() = runTest {
        val api = MosaicApi(FakeTransport(rule({ true }) { response(404, """{"error":"404 Not Found","message":"memo not found"}""") }))
        val e = runCatching { api.getMemo("missing") }.exceptionOrNull()
        assertTrue(e is HttpException)
        assertEquals("memo not found", (e as HttpException).message2)
    }

    @Test
    fun `update memo encodes explicit nulls to clear fields`() = runTest {
        var captured: ApiRequest? = null
        val api = MosaicApi(FakeTransport(rule({ true }) { req ->
            captured = req
            response(200, MEMO_JSON)
        }))
        api.updateMemo(
            "uuid-1",
            buildJsonObject {
                put("diaryDate", kotlinx.serialization.json.JsonNull)
                put("content", JsonPrimitive("更新后的内容"))
            },
        )
        val body = captured!!.bodyUtf8()!!
        assertTrue(body.contains("\"diaryDate\":null"))
        assertTrue(body.contains("\"content\":\"更新后的内容\""))
    }
}

